import { defineConfig, devices } from "@playwright/test";
import dotenv from "dotenv";
import path from "path";
import crypto from "crypto";

dotenv.config({ path: path.resolve(__dirname, ".env") });

// 1. Explicitly require and validate E2E_DATABASE_URL
const e2eDbUrl = process.env.E2E_DATABASE_URL;
if (!e2eDbUrl || typeof e2eDbUrl !== "string" || e2eDbUrl.trim() === "") {
  throw new Error(
    "FATAL_E2E_CONFIGURATION_ERROR: process.env.E2E_DATABASE_URL is not set. An explicit E2E database URL targeting 'crediguide_e2e_db' is strictly required."
  );
}

let dbName: string | null = null;
try {
  const parsed = new URL(e2eDbUrl);
  dbName = parsed.pathname.replace(/^\//, "").split("?")[0] || null;
} catch (err: unknown) {
  const msg = err instanceof Error ? err.message : String(err);
  throw new Error(`FATAL_E2E_CONFIGURATION_ERROR: Malformed E2E_DATABASE_URL: ${msg}`);
}

if (dbName !== "crediguide_e2e_db") {
  throw new Error(
    `FATAL_E2E_CONFIGURATION_ERROR: E2E_DATABASE_URL must target 'crediguide_e2e_db', but targets '${dbName}'. Execution aborted to protect database integrity.`
  );
}

// 2. Unconditionally generate a fresh 32-byte cryptographically random secret for every Playwright run.
// In the main orchestrator process, generate a new secret ignoring any pre-existing environment variable.
// In Playwright child worker processes (TEST_WORKER_INDEX is defined), inherit the exact secret generated by the orchestrator.
const isWorkerProcess =
  process.env.TEST_WORKER_INDEX !== undefined ||
  process.env.PW_TEST_WORKER_INDEX !== undefined;

let ephemeralBridgeSecret: string;
if (isWorkerProcess && process.env.E2E_BRIDGE_SECRET) {
  ephemeralBridgeSecret = process.env.E2E_BRIDGE_SECRET;
} else {
  ephemeralBridgeSecret = crypto.randomBytes(32).toString("hex");
  process.env.E2E_BRIDGE_SECRET = ephemeralBridgeSecret;
}

export default defineConfig({
  testDir: "./e2e",
  fullyParallel: false,
  forbidOnly: !!process.env.CI,
  retries: 0,
  workers: 1,
  reporter: [["list"]],
  timeout: 45000,
  use: {
    baseURL: "http://localhost:3000",
    trace: "on-first-retry",
    headless: true,
  },
  projects: [
    {
      name: "Google Chrome",
      use: {
        ...devices["Desktop Chrome"],
        channel: "chrome",
      },
    },
  ],
  webServer: {
    command: "npm run dev",
    url: "http://localhost:3000",
    reuseExistingServer: false, // Strictly false: never reuse a server that might be running on crediguide_db
    timeout: 120000,
    env: {
      IS_E2E: "true",
      ENABLE_E2E_EMAIL_BRIDGE: "true",
      E2E_DATABASE_URL: e2eDbUrl,
      E2E_BRIDGE_SECRET: ephemeralBridgeSecret,
    },
  },
});
